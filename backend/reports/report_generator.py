
from pathlib import Path
from html import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def create_pdf_report(correlation, confidence, output_path=None):
    """
    Generate a PDF forensic analysis report.
    """

    # Save reports in the project's root reports folder
    if output_path is None:
        project_root = Path(__file__).resolve().parents[2]
        reports_folder = project_root / "reports"
        reports_folder.mkdir(parents=True, exist_ok=True)
        output_path = reports_folder / "truthlens_report.pdf"
    else:
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)

    document = SimpleDocTemplate(
        str(output_path),
        pagesize=A4,
        rightMargin=50,
        leftMargin=50,
        topMargin=50,
        bottomMargin=50
    )

    styles = getSampleStyleSheet()
    story = []

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        textColor=colors.HexColor("#17365D"),
        fontSize=22,
        spaceAfter=12
    )

    heading_style = styles["Heading2"]
    normal_style = styles["BodyText"]

    # Report title
    story.append(Paragraph("TRUTHLENS", title_style))
    story.append(
        Paragraph("Multimodal Digital Forensics Report", styles["Heading2"])
    )
    story.append(Spacer(1, 0.2 * inch))

    # Analysis information
    story.append(Paragraph("1. Analysis Summary", heading_style))

    summary_data = [
        ["Analysis Type", str(correlation.get("analysis_type", "N/A"))],
        ["Timestamp", str(correlation.get("timestamp", "N/A"))],
        ["Agreement", str(correlation.get("agreement", "N/A"))],
        [
            "Suspicious Modalities",
            ", ".join(correlation.get("suspicious_modalities", [])) or "None"
        ],
        [
            "Available Modalities",
            ", ".join(correlation.get("available_modalities", [])) or "None"
        ],
        [
            "Unavailable Modalities",
            ", ".join(correlation.get("unavailable_modalities", [])) or "None"
        ]
    ]

    summary_table = Table(summary_data, colWidths=[150, 330])
    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#DCE6F1")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("PADDING", (0, 0), (-1, -1), 8)
    ]))

    story.append(summary_table)
    story.append(Spacer(1, 0.2 * inch))

    # Findings
    story.append(Paragraph("2. Detection Findings", heading_style))

    findings = correlation.get("findings", [])

    if findings:
        for finding in findings:
            modality = escape(str(finding.get("modality", "Unknown")))
            indicator = escape(str(finding.get("indicator", "N/A")))

            story.append(
                Paragraph(
                    f"<b>{modality.upper()}:</b> {indicator}",
                    normal_style
                )
            )
            story.append(Spacer(1, 6))
    else:
        story.append(Paragraph("No findings were provided.", normal_style))

    story.append(Spacer(1, 0.2 * inch))

    # Confidence summary
    story.append(Paragraph("3. Confidence Analysis", heading_style))

    average = confidence.get("average_detector_confidence")

    if average is not None:
        confidence_text = f"{average * 100:.1f}%"
    else:
        confidence_text = "Not available"

    story.append(
        Paragraph(
            f"Average detector confidence: <b>{confidence_text}</b>",
            normal_style
        )
    )

    story.append(
        Paragraph(
            f"Evidence coverage: "
            f"{escape(str(confidence.get('evidence_coverage', 'N/A')))}",
            normal_style
        )
    )

    story.append(Spacer(1, 0.2 * inch))

    # Explanation and limitations
    story.append(Paragraph("4. Interpretation", heading_style))

    explanation = escape(
        str(correlation.get("explanation", "No explanation available."))
    )
    story.append(Paragraph(explanation, normal_style))
    story.append(Spacer(1, 12))

    warning = escape(
        str(confidence.get(
            "warning",
            "Results require further verification."
        ))
    )

    story.append(
        Paragraph(f"<b>Important limitation:</b> {warning}", normal_style)
    )

    story.append(Spacer(1, 0.3 * inch))
    story.append(
        Paragraph(
            "Generated by TruthLens. This report presents automated "
            "analysis results and should not be treated as definitive "
            "proof of authenticity or manipulation.",
            styles["Italic"]
        )
    )

    document.build(story)

    return str(output_path)
